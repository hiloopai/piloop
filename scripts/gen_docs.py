"""Generate the reference pages of the docs site and the trigger SQL. ``--check`` fails when a file is stale.

- ``docs/reference/configuration.mdx`` from ``piloop.config.ProjectConfig``.
- ``docs/reference/schema.mdx`` from the models in ``piloop/db/models.py``.
- ``piloop/db/actor_triggers.sql`` from ``piloop.db.triggers.TEMP``. Every connection loads it.
- ``piloop/db/persistent_triggers.sql`` from ``PERSISTENT``: a snapshot of what the migrations install, so that a
  trigger change shows up in a review as SQL.
"""

import inspect
import json
import re
import sys
from pathlib import Path
from typing import Any, get_args

from pydantic import BaseModel
from pydantic.json_schema import GenerateJsonSchema

from piloop.config import ProjectConfig
from piloop.db.sql import schema_ddl
from piloop.db.triggers import persistent_sql, temp_sql
from piloop.deprecated import BRIDGES

ROOT = Path(__file__).resolve().parent.parent
CONFIG_PAGE = ROOT / 'docs' / 'reference' / 'configuration.mdx'
SCHEMA_PAGE = ROOT / 'docs' / 'reference' / 'schema.mdx'
ACTOR_SQL = ROOT / 'piloop' / 'db' / 'actor_triggers.sql'
PERSISTENT_SQL = ROOT / 'piloop' / 'db' / 'persistent_triggers.sql'
REPO = 'https://github.com/hiloopai/piloop/blob/main'
JsonSchema = dict[str, Any]  # JSON Schema is untyped by nature

GENERATED = '{/* Generated by scripts/gen_docs.py. Do not edit this file: change the source and run `make docs`. */}'
CONFIG_HEADER = f"""---
title: Configuration
description: Every key of piloop.toml, with its type and its default.
---

{GENERATED}

`piloop.toml` is at the root of the project repo. `piloop init` reads it again each time you run it.

To override a key for one process, set `PILOOP_PROJECT_<KEY>`. Join nested keys with `__`, for example
`PILOOP_PROJECT_RUNTIME=subprocess` or `PILOOP_PROJECT_ROLES__WORKER__MAX_CONCURRENT=2`.

A type in the tables links to the section that describes it. A table that you leave out has the defaults of its
section.

## Top-level keys

"""
SCHEMA_HEADER = f"""---
title: Database schema
description: The tables that piloop sql reads and writes.
---

{GENERATED}

Every client reads and writes one SQLite database, `$PILOOP_HOME/piloop.db`. Run one statement with `piloop sql`.
`piloop schema` prints the same tables with the conventions that agents follow. The agents' procedures are in
[sql_procedures.md]({REPO}/piloop/agents/prompts/sql_procedures.md).

The indexes are part of the contract: they show which filters are cheap.

```sql
"""
CODE = re.compile(r'(``.+?``|`[^`]+`)')


def mdx(text: str) -> str:
    """Make docstring text safe for MDX: code spans with one backtick, and ``{}<>`` escaped outside code."""
    out = []
    for i, part in enumerate(CODE.split(text)):
        if i % 2:
            out.append(f'`{part.strip("`")}`')
        else:
            out.append(re.sub(r'([{}<>])', r'\\\1', part))
    return ''.join(out)


def cell(text: str) -> str:
    """Make text safe for one cell of a Markdown table."""
    return mdx(' '.join(text.split())).replace('|', '\\|')


def _anchor(name: str) -> str:
    return f'[{name}](#{name.lower()})'


def _type(prop: JsonSchema, defs: JsonSchema) -> str:
    if '$ref' in prop:
        name = str(prop['$ref']).rsplit('/', 1)[-1]
        target = defs[name]
        return _anchor(name) if 'properties' in target else _type(target, defs)
    if 'anyOf' in prop:
        return ' \\| '.join(_type(p, defs) for p in prop['anyOf'])
    if 'enum' in prop:
        return ' \\| '.join(f'`{v}`' for v in prop['enum'])
    t = str(prop.get('type', 'object'))
    if t == 'array' and 'prefixItems' in prop:  # a fixed-shape tuple
        return f'tuple\\[{", ".join(_type(p, defs) for p in prop["prefixItems"])}\\]'
    if t == 'array':
        return f'list\\[{_type(prop["items"], defs)}\\]'
    if t == 'object' and 'additionalProperties' in prop:
        return f'dict\\[string, {_type(prop["additionalProperties"], defs)}\\]'
    return t


def _default(name: str, prop: JsonSchema, schema: JsonSchema) -> str:
    if name in schema.get('required', []):
        return 'required'
    if '$ref' in prop and isinstance(prop.get('default'), dict):
        return '`{}`'  # a nested table left out: every key at the default that its own table shows
    return f'`{json.dumps(prop.get("default"))}`'


def _table(schema: JsonSchema, defs: JsonSchema, only: set[str] | None = None) -> str:
    rows = ['| Key | Type | Default | Description |', '|---|---|---|---|']
    for name, prop in schema['properties'].items():
        if only is not None and name not in only:
            continue
        desc = cell(str(prop.get('description', '')))
        rows.append(f'| `{name}` | {_type(prop, defs)} | {_default(name, prop, schema)} | {desc} |')
    return '\n'.join(rows) + '\n'


def _schema(model: type[BaseModel]) -> JsonSchema:
    return model.model_json_schema(schema_generator=GenerateJsonSchema)


def _section(model: type[BaseModel], defs: JsonSchema, only: set[str] | None = None) -> str:
    schema = _schema(model)
    return f'\n## {model.__name__}\n\n{mdx(schema.get("description", ""))}\n\n{_table(schema, defs, only)}'


def _nested(model: type[BaseModel], found: list[type[BaseModel]]) -> list[type[BaseModel]]:
    """Return the models reachable from the fields of ``model``, in declaration order, each once."""
    for field in model.model_fields.values():
        for sub in _models_in(field.annotation):
            if sub not in found:
                found.append(sub)
                _nested(sub, found)
    return found


def _models_in(annotation: object) -> list[type[BaseModel]]:
    if isinstance(annotation, type) and issubclass(annotation, BaseModel):
        return [annotation]
    return [m for arg in get_args(annotation) for m in _models_in(arg)]


def _own_keys(model: type[BaseModel], base: type[BaseModel]) -> set[str]:
    """Return the keys that ``model`` adds to ``base`` or gives another default."""
    mine, theirs = _schema(model)['properties'], _schema(base)['properties']
    return {name for name, prop in mine.items() if theirs.get(name) != prop}


def config_page() -> str:
    """Return the configuration reference: the top-level keys, then one table per nested model.

    A model that subclasses another config model gets the table of its base once (the keys that they share), and
    then a table of its own keys and defaults.
    """
    top = _schema(ProjectConfig)
    defs = top.get('$defs', {})
    out = CONFIG_HEADER + _table(top, defs)
    shown: list[type[BaseModel]] = []
    for model in _nested(ProjectConfig, []):
        base = model.__mro__[1]
        if base is BaseModel or not issubclass(base, BaseModel):
            out += _section(model, defs)
            continue
        if base not in shown:
            shown.append(base)
            out += _section(base, defs)
        out += _section(model, defs, _own_keys(model, base))
    return out + deprecated_section()


def deprecated_section() -> str:
    """Return the keys that ``piloop.deprecated`` still accepts, one bullet per bridge; nothing when there are none."""
    if not BRIDGES:
        return ''
    bullets = '\n'.join(f'- {mdx(" ".join(str(inspect.getdoc(b)).split()))}' for b in BRIDGES)
    return (
        '\n## Deprecated keys\n\nThese keys still work. Each one shows a `PiloopDeprecationWarning` that names the file,'
        ' the key, its replacement and the release that removes it. The changelog lists them too.\n\n'
        f'{bullets}\n'
    )


def main(check: bool) -> int:
    """Write every generated file, or with ``check`` report the stale ones and write nothing."""
    outputs = {
        CONFIG_PAGE: config_page(),
        SCHEMA_PAGE: SCHEMA_HEADER + schema_ddl() + '\n```\n',
        ACTOR_SQL: temp_sql(),
        PERSISTENT_SQL: persistent_sql(),
    }
    stale = [p for p, text in outputs.items() if not p.is_file() or p.read_text() != text]
    if check:
        for p in stale:
            print(f'stale: {p.relative_to(ROOT)} (run `make docs`)', file=sys.stderr)
        return 1 if stale else 0
    for p, text in outputs.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main(check='--check' in sys.argv[1:]))
